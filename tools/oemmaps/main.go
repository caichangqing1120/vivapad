package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"strconv"
	"strings"
)

var sourceHashes = map[int]string{
	720: "4868b0058d0bdecacc91d457b8c83a5cf862492cc8de498e91d1c8cd9e1f7d6f",
	737: "4ddd7f42d0335de651ff17793df2f71d3e5d95f05369f937c515fb9c92b2a751",
	775: "3e8b215a25ea9854eed73130beab98631483c0758430b6d84c4fd15e74f055d6",
	857: "9b6e7a75744a103e12d54182edfa3597b225bdd2ba791cef0570fd1142abe933",
	861: "5eaf9209974721b1e73af5428c565e554c787b155f94f163cdd468bf695b3dd2",
	869: "892070a0ab10783783d7e7ffec5c19767e17e23eaf1f221659692d9447dddb37",
}

const pythonSource = `import codecs
for code in (720, 737, 775, 857, 861, 869):
    for byte in range(256):
        try:
            value = ord(bytes([byte]).decode("cp{}".format(code), "strict"))
        except UnicodeDecodeError:
            value = -1
        print("{}\t{}\t{}".format(code, byte, value))
`

func main() {
	output := flag.String("out", "oem_tables_generated.go", "generated Go file")
	flag.Parse()
	if err := generate(*output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(path string) error {
	data, err := exec.Command("python3", "-c", pythonSource).Output()
	if err != nil {
		return fmt.Errorf("read CPython OEM codecs: %w", err)
	}
	tables := make(map[int]*[256]int, len(sourceHashes))
	seen := make(map[int]*[256]bool, len(sourceHashes))
	for code := range sourceHashes {
		tables[code], seen[code] = new([256]int), new([256]bool)
	}
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		parts := strings.Split(scanner.Text(), "\t")
		if len(parts) != 3 {
			return fmt.Errorf("invalid codec row %q", scanner.Text())
		}
		code, codeError := strconv.Atoi(parts[0])
		index, indexError := strconv.Atoi(parts[1])
		value, valueError := strconv.Atoi(parts[2])
		table, known := tables[code]
		if codeError != nil || indexError != nil || valueError != nil || !known || index < 0 || index > 255 ||
			value < -1 || value > 0x10ffff || seen[code][index] {
			return fmt.Errorf("invalid or repeated codec row %q", scanner.Text())
		}
		table[index], seen[code][index] = value, true
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	var source bytes.Buffer
	source.WriteString("// Code generated by tools/oemmaps from CPython 3.14.6 codecs; DO NOT EDIT.\n")
	source.WriteString("// CP720 was generated on Windows Vista; the others use Unicode MICSFT/PC mappings.\n\n")
	source.WriteString("package document\n\n")
	for _, code := range []int{720, 737, 775, 857, 861, 869} {
		values := make([]string, 256)
		for index, value := range tables[code] {
			if !seen[code][index] {
				return fmt.Errorf("CP%d has no mapping row %02x", code, index)
			}
			values[index] = strconv.Itoa(value)
		}
		digest := fmt.Sprintf("%x", sha256.Sum256([]byte(strings.Join(values, ","))))
		if digest != sourceHashes[code] {
			return fmt.Errorf("CP%d mapping changed: %s", code, digest)
		}
		fmt.Fprintf(&source, "var cp%dTable = [256]rune{\n", code)
		for index, value := range tables[code] {
			if index%8 == 0 {
				source.WriteByte('\t')
			}
			if value < 0 {
				source.WriteString("-1,")
			} else {
				fmt.Fprintf(&source, "0x%04x,", value)
			}
			if index%8 == 7 {
				source.WriteByte('\n')
			}
		}
		source.WriteString("}\n\n")
	}
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0644)
}
