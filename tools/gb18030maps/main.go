package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	_ "embed"
	"encoding/binary"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"sort"
	"strconv"
	"strings"
)

const mappingDigest = "e47898ee197ed3f428e0dc76ce300a070126e7301b5d1491b0d3c0262d623af2"

//go:embed ICU-LICENSE.txt
var license string

const pythonSource = `for lead in range(0x81,0xff):
 for trail in list(range(0x40,0x7f))+list(range(0x80,0xff)):
  value=bytes([lead,trail]).decode("gb18030","strict")
  if len(value)==1 and 0xe000<=ord(value)<=0xf8ff:
   print("{}\t{}".format(ord(value),(lead<<8)|trail))
`

type entry struct{ scalar, pointer int }
type interval struct{ scalar, pointer, count int }

func main() {
	output := flag.String("out", "gb18030_table_generated.go", "generated Go file")
	flag.Parse()
	if err := generate(*output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(file string) error {
	data, err := exec.Command("python3", "-c", pythonSource).Output()
	if err != nil {
		return fmt.Errorf("read CPython GB18030 mappings: %w", err)
	}
	var entries []entry
	seenScalar, seenPair := make(map[int]bool), make(map[int]bool)
	digest := sha256.New()
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		fields := strings.Fields(scanner.Text())
		if len(fields) != 2 {
			return fmt.Errorf("invalid mapping row %q", scanner.Text())
		}
		scalar, scalarErr := strconv.Atoi(fields[0])
		pair, pairErr := strconv.Atoi(fields[1])
		lead, trail := pair>>8, pair&0xff
		if scalarErr != nil || pairErr != nil || scalar < 0xe000 || scalar > 0xf8ff || lead < 0x81 || lead > 0xfe || trail < 0x40 || trail > 0xfe || trail == 0x7f || seenScalar[scalar] || seenPair[pair] {
			return fmt.Errorf("invalid or ambiguous mapping row %q", scanner.Text())
		}
		seenScalar[scalar], seenPair[pair] = true, true
		digest.Write([]byte{byte(lead), byte(trail)})
		var value [4]byte
		binary.BigEndian.PutUint32(value[:], uint32(scalar))
		digest.Write(value[:])
		pointer := (lead-0x81)*190 + trail - 0x40
		if trail >= 0x80 {
			pointer--
		}
		entries = append(entries, entry{scalar, pointer})
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	if len(entries) != 2068 || fmt.Sprintf("%x", digest.Sum(nil)) != mappingDigest {
		return fmt.Errorf("GB18030 table differs from the pinned ICU-2000 roundtrip PUA set")
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].scalar < entries[j].scalar })
	var ranges []interval
	for _, item := range entries {
		if len(ranges) > 0 {
			last := &ranges[len(ranges)-1]
			if last.scalar+last.count == item.scalar && last.pointer+last.count == item.pointer {
				last.count++
				continue
			}
		}
		ranges = append(ranges, interval{item.scalar, item.pointer, 1})
	}
	if len(ranges) > 256 {
		return fmt.Errorf("too many GB18030 ranges for the decoder index")
	}
	indices := make([]int, len(ranges))
	for i := range indices {
		indices[i] = i
	}
	sort.Slice(indices, func(i, j int) bool { return ranges[indices[i]].pointer < ranges[indices[j]].pointer })
	var source bytes.Buffer
	source.WriteString("// Code generated by tools/gb18030maps; DO NOT EDIT.\n")
	source.WriteString("// GB18030-2000 PUA mappings from ICU 3.4 commit 28d7ae26c99baf18459e5111c0020c8919867b82.\n")
	source.WriteString("// Source: source/data/mappings/gb18030.ucm, SHA256 6578d0697f3e1a91d75b2402db78a19e5acba6a930ded31b08948a1162001c66.\n")
	fmt.Fprintf(&source, "// CPython output is accepted only when its pair+BE32rune digest is %s.\n\n/*\n%s*/\n\npackage document\n\n", mappingDigest, license)
	source.WriteString("var gb18030PUARanges = [...]gb18030PUARange{\n")
	for _, item := range ranges {
		fmt.Fprintf(&source, "{0x%04x,0x%04x,%d},\n", item.scalar, item.pointer, item.count)
	}
	source.WriteString("}\n\nvar gb18030PUAByPointer = [...]uint8{\n")
	for _, index := range indices {
		fmt.Fprintf(&source, "%d,", index)
	}
	source.WriteString("\n}\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(file, formatted, 0o644)
}
